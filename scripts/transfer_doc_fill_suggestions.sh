#!/usr/bin/env bash
#
# Transfers "lost" document metadata (fileName / publicationDate) recovered
# from DALA-4405 (removal of dataSource.fileName/publicationDate from
# datapoints) into the document-manager, via
#   PATCH /documents/{documentId}
# for every row in a doc_fill_suggestions.csv file.
#
# CSV columns (produced upstream, see temp/doc_fill_suggestions.csv):
#   document_id,current_file_name,suggested_file_name,current_publication_date,
#   suggested_publication_date,fields_filled
#
# For each row:
#   - if fields_filled contains "fileName", suggested_file_name is sent as
#     documentName
#   - if fields_filled contains "publicationDate", suggested_publication_date
#     is sent as publicationDate
#   - if fields_filled contains both, both are sent in the same PATCH call
#
# Intended to be run manually, once per environment, in this order:
#   clone.dataland.com -> test.dataland.com -> dataland.com
#
# Usage:
#   DATALAND_BASE_URL="https://clone.dataland.com" \
#   DATALAND_API_KEY="<api key generated by a data_admin user on that environment>" \
#     ./scripts/transfer_doc_fill_suggestions.sh [--dry-run] [path/to/doc_fill_suggestions.csv]
#
# Required environment variables:
#   DATALAND_BASE_URL  Base URL of the target environment, e.g. https://clone.dataland.com
#   DATALAND_API_KEY   API key of a user with ROLE_ADMIN on that environment
#                       (generate via Swagger UI / POST /api-keys/generateApiKey)
#
# Optional:
#   --dry-run          Print what would be sent, without performing any PATCH calls.
#   CSV path defaults to temp/doc_fill_suggestions.csv relative to the repo root.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
PARSE_HELPER="$SCRIPT_DIR/parse_doc_fill_suggestions.py"

DRY_RUN=false
CSV_PATH="$REPO_ROOT/temp/doc_fill_suggestions.csv"

for arg in "$@"; do
  case "$arg" in
    --dry-run)
      DRY_RUN=true
      ;;
    -h|--help)
      sed -n '2,32p' "${BASH_SOURCE[0]}"
      exit 0
      ;;
    *)
      CSV_PATH="$arg"
      ;;
  esac
done

if [[ -z "${DATALAND_BASE_URL:-}" ]]; then
  echo "Error: DATALAND_BASE_URL is not set (e.g. https://clone.dataland.com)." >&2
  exit 1
fi

if [[ "$DRY_RUN" == false && -z "${DATALAND_API_KEY:-}" ]]; then
  echo "Error: DATALAND_API_KEY is not set." >&2
  exit 1
fi

if [[ ! -f "$CSV_PATH" ]]; then
  echo "Error: CSV file not found at '$CSV_PATH'." >&2
  exit 1
fi

for cmd in python3 jq curl; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "Error: required command '$cmd' is not available." >&2
    exit 1
  fi
done

BASE_URL="${DATALAND_BASE_URL%/}"
TIMESTAMP="$(date +%Y%m%dT%H%M%S)"
FAILURES_LOG="$REPO_ROOT/scripts/transfer_doc_fill_suggestions_failures_${TIMESTAMP}.log"

total=0
succeeded=0
failed=0

echo "Base URL:  $BASE_URL"
echo "CSV file:  $CSV_PATH"
echo "Dry run:   $DRY_RUN"
echo "Failures log: $FAILURES_LOG"
echo

US=$'\x1f'

while IFS="$US" read -r document_id fields_filled suggested_file_name suggested_publication_date; do
  total=$((total + 1))

  json_args=(-n)
  set_fields=()
0
  if [[ "$fields_filled" == *"fileName"* ]]; then
    json_args+=(--arg documentName "$suggested_file_name")
    set_fields+=('documentName: $documentName')
  fi
  if [[ "$fields_filled" == *"publicationDate"* ]]; then
    json_args+=(--arg publicationDate "$suggested_publication_date")
    set_fields+=('publicationDate: $publicationDate')
  fi

  if [[ ${#set_fields[@]} -eq 0 ]]; then
    echo "  [$document_id] Skipping: unrecognized fields_filled value '$fields_filled'." >&2
    failed=$((failed + 1))
    echo "$document_id  unrecognized fields_filled='$fields_filled'" >>"$FAILURES_LOG"
    continue
  fi

  jq_filter="{ $(IFS=,; echo "${set_fields[*]}") }"
  body="$(jq "${json_args[@]}" "$jq_filter")"

  if [[ "$DRY_RUN" == true ]]; then
    echo "  [$document_id] PATCH $BASE_URL/documents/$document_id"
    echo "    body: $body"
    succeeded=$((succeeded + 1))
    continue
  fi

  response="$(curl --silent --show-error --insecure \
    --request PATCH \
    "$BASE_URL/documents/$document_id" \
    --header "Authorization: Bearer $DATALAND_API_KEY" \
    --header "Content-Type: application/json" \
    --data "$body" \
    --write-out $'\n%{http_code}')"

  http_code="${response##*$'\n'}"
  response_body="${response%$'\n'*}"

  if [[ "$http_code" =~ ^2[0-9][0-9]$ ]]; then
    succeeded=$((succeeded + 1))
    echo "  [$document_id] OK ($http_code)"
  else
    failed=$((failed + 1))
    echo "  [$document_id] FAILED ($http_code)" >&2
    {
      echo "document_id: $document_id"
      echo "http_code:   $http_code"
      echo "request:     $body"
      echo "response:    $response_body"
      echo "---"
    } >>"$FAILURES_LOG"
  fi

  if (( total % 100 == 0 )); then
    echo "  ... processed $total rows so far ($succeeded ok, $failed failed)"
  fi
done < <(python3 "$PARSE_HELPER" "$CSV_PATH")

echo
echo "Done. Total: $total, succeeded: $succeeded, failed: $failed."
if [[ "$failed" -gt 0 ]]; then
  echo "See $FAILURES_LOG for details on failed rows."
  exit 1
else
  # Remove empty failures log if nothing failed.
  rm -f "$FAILURES_LOG"
fi
